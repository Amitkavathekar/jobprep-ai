import { model, Schema } from "mongoose";

const AdminSchema = new Schema(
  {
    adminId: {
      type: String,
      required: true,
      unique: true,
    },

    name: {
      type: String,
      required: true,
      trim: true,
    },

    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
    },

    passwordHash: {
      type: String,
      required: true,
    },
  }
);

export const AdminModel = model("Admin", AdminSchema);
